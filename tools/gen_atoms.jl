# ORIGINAL: generates the built-in atom and functor tables (src/pl-atom.jl, src/pl-funct.jl) from
# swipl-devel's src/ATOMS, as upstream's `defatom` (src/defatom.c) generates pl-atom.ic and
# pl-funct.ic at build time.
# tools/gen_atoms.jl — upstream's built-in atoms are GENERATED: `defatom` reads src/ATOMS and writes
# `ATOM("")` first (so the empty atom is index 1), then one `ATOM("<text>")` per `A` line, in file
# order; `registerBuiltinAtoms` (pl-atom.c) loads them in that order, so a built-in atom's index is
# its position. This tool reads src/ATOMS AT THE PIN — `git show <commit>:src/ATOMS`, the commit
# from tools/SWIPL_VERSION, never the checkout's working tree (which may sit at another commit: the
# dev-zone checkout was at the previous pin when this was written, with two atoms fewer) — and
# rewrites the region between the markers in src/pl-atom.jl. test/core_lang/test_atom_table.jl
# checks the region against this tool whenever a checkout is present.
#
#   julia --project=. tools/gen_atoms.jl [--check] [path/to/swipl-devel]   # default ~/dev-zone/…
#   (--check: exit 1 if src/pl-atom.jl differs from what src/ATOMS gives; write nothing)

const _PATHS = filter(a -> !startswith(a, "--"), ARGS)
const _UPSTREAM = if !isempty(_PATHS)
    _PATHS[1]
else
    get(ENV, "LOGICKERNEL_UPSTREAM_SWIPL_DEVEL", joinpath(homedir(), "dev-zone", "swipl-devel"))
end
const _ROOT = joinpath(@__DIR__, "..")
const BEGIN_MARK = "# ── GENERATED by tools/gen_atoms.jl from src/ATOMS — do not edit up to END GENERATED ──"
const END_MARK = "# ── END GENERATED ──"
const FBEGIN_MARK = "# ── GENERATED by tools/gen_atoms.jl from src/ATOMS (functors) — do not edit up to END GENERATED ──"

"The pinned swipl-devel commit (tools/SWIPL_VERSION's `commit:` line)."
function pinned_commit(root::AbstractString=_ROOT)::String
    for l in eachline(joinpath(root, "tools", "SWIPL_VERSION"))
        m = match(r"^commit:\s*([0-9a-f]{40})\s*$", l)
        m === nothing || return String(m[1])
    end
    error("tools/SWIPL_VERSION: no `commit:` line")
end

"""
The text of a C string literal's body as `defatom` copies it into pl-atom.ic: the only escape the
file uses is `\\\\` (one backslash). Any other backslash sequence is REFUSED — a new escape upstream
must fail the generator, not become a wrong atom.
"""
function c_unescape(s::AbstractString, where::AbstractString)::String
    out = IOBuffer()
    i = firstindex(s)
    while i <= lastindex(s)
        c = s[i]
        if c == '\\'
            j = nextind(s, i)
            (j <= lastindex(s) && s[j] == '\\') ||
                error(
                    "$where: escape `\\$(j <= lastindex(s) ? s[j] : "")` — only `\\\\` is handled"
                )
            write(out, '\\')
            i = nextind(s, j)
        else
            write(out, c)
            i = nextind(s, i)
        end
    end
    return String(take!(out))
end

"""
The built-in atoms from the text of src/ATOMS, as `defatom` numbers them: `(ids, texts)`, index 1
the empty atom (`ATOM_`), then every `A <id> "<text>"` line in file order. Lines are parsed as
`sscanf("A%s \\"%[^\\"]\\"")` does: an id, then the text up to the next `"`.
"""
function parse_atoms(src::AbstractString)::Tuple{Vector{String}, Vector{String}}
    ids, texts = String[""], String[""]
    for (n, l) in enumerate(split(src, '\n'))
        startswith(l, 'A') || continue
        m = match(r"^A\s*(\S+)\s+\"([^\"]*)\"", l)     # `%s` skips leading white space
        m === nothing && error("ATOMS:$n: syntax error")
        push!(ids, String(m[1]))
        push!(texts, c_unescape(m[2], "ATOMS:$n"))
    end
    return ids, texts
end

"""
The built-in functors of src/ATOMS as `defatom` numbers them, from 1 in `F` line order:
`(id, arity)` each (`FUNCTOR(ATOM_<id>, arity)`), parsed as `sscanf("F%s%d")` does. Stage A
only checks them (`--check` reports the count); stage B generates the functor table from them.
"""
function parse_functors(src::AbstractString)::Vector{Tuple{String, Int}}
    fs = Tuple{String, Int}[]
    for (n, l) in enumerate(split(src, '\n'))
        startswith(l, 'F') || continue
        m = match(r"^F\s*(\S+)\s+(\d+)", l)
        m === nothing && error("ATOMS:$n: syntax error")
        push!(fs, (String(m[1]), parse(Int, m[2])))
    end
    return fs
end

"A Julia string literal for `s` (every character outside printable ASCII escaped)."
jl_literal(s::AbstractString)::String = repr(String(s))

"The generated region (both markers included) for the atoms `ids`, `texts` read at `commit`."
function region(ids::Vector{String}, texts::Vector{String}, commit::AbstractString)::String
    io = IOBuffer()
    println(io, BEGIN_MARK)
    println(
        io,
        "# src/ATOMS @ ",
        commit[1:12],
        ": ",
        length(texts),
        " built-in atoms, index 1 first."
    )
    println(io, "\"The built-in atoms' texts (pl-atom.ic, `defatom`), by index.\"")
    println(io, "const _BUILTIN_ATOMS = (")
    for (k, t) in enumerate(texts)                   # Blue: no comma after the last
        println(io, "    ", jl_literal(t), k < length(texts) ? "," : "")
    end
    println(io, ")")
    println(
        io,
        "\"The built-in atoms' ids (`ATOM_<id>`, pl-atom.ih), by index: the empty id for `ATOM_`.\""
    )
    println(io, "const _BUILTIN_ATOM_IDS = (")
    for (k, id) in enumerate(ids)                   # Blue: no comma after the last
        println(io, "    ", jl_literal(id), k < length(ids) ? "," : "")
    end
    println(io, ")")
    print(io, END_MARK)
    return String(take!(io))
end

"""
The generated region (both markers included) of the built-in functors `fs` (`(id, arity)` in `F`
line order, `parse_functors`), each as `(the index of atom ATOM_<id>, arity)` — upstream's
`FUNCTOR(ATOM_<id>, arity)` of pl-funct.ic, numbered from 1 by `registerFunctor`.
"""
function functor_region(
    fs::Vector{Tuple{String, Int}}, ids::Vector{String}, commit::AbstractString
)::String
    io = IOBuffer()
    println(io, FBEGIN_MARK)
    println(
        io,
        "# src/ATOMS @ ",
        commit[1:12],
        ": ",
        length(fs),
        " built-in functors, index 1 first."
    )
    println(
        io,
        "\"The built-in functors (pl-funct.ic, `defatom`), by index: (atom index of the name, arity).\""
    )
    println(io, "const _BUILTIN_FUNCTORS = (")
    for (k, (id, arity)) in enumerate(fs)            # Blue: no comma after the last
        a = findfirst(==(id), ids)
        a === nothing && error("ATOMS: functor $id/$arity names no atom")
        println(io, "    (", a, ", ", arity, ")", k < length(fs) ? "," : "")
    end
    println(io, ")")
    print(io, END_MARK)
    return String(take!(io))
end

"`file` with the generated region opened by `begin_mark` replaced by `reg`."
function rewrite(
    file::AbstractString, reg::AbstractString; begin_mark::AbstractString=BEGIN_MARK
)::String
    s = read(file, String)
    i = findfirst(begin_mark, s)
    j = findfirst(END_MARK, s)
    (i === nothing || j === nothing) && error("$file: the GENERATED markers are missing")
    count(begin_mark, s) == 1 && count(END_MARK, s) == 1 ||
        error("$file: the GENERATED markers must appear once each")
    return s[1:prevind(s, first(i))] * reg * s[nextind(s, last(j)):end]
end

"The atoms of src/ATOMS at the pin, read from the checkout `upstream`'s object store."
function atoms_at_pin(upstream::AbstractString, commit::AbstractString)
    src = read(`git -C $upstream show $commit:src/ATOMS`, String)
    return parse_atoms(src)
end

if abspath(PROGRAM_FILE) == @__FILE__
    commit = pinned_commit()
    ids, texts = atoms_at_pin(_UPSTREAM, commit)
    file = joinpath(_ROOT, "src", "pl-atom.jl")
    new = rewrite(file, region(ids, texts, commit))
    fs = parse_functors(read(`git -C $_UPSTREAM show $commit:src/ATOMS`, String))
    ffile = joinpath(_ROOT, "src", "pl-funct.jl")
    fnew = rewrite(ffile, functor_region(fs, ids, commit); begin_mark=FBEGIN_MARK)
    if "--check" in ARGS
        ids_set = Set(ids)
        missing = [f for (f, _) in fs if !(f in ids_set)]          # "A name should exist as well"
        println(
            "gen_atoms: src/ATOMS @ $(commit[1:12]): $(length(texts)) atoms (the empty atom ",
            "first), $(length(fs)) functors (numbered from 1)")
        isempty(missing) ||
            (println("gen_atoms: functors without an atom: ", missing); exit(1))
        same = new == read(file, String)
        fsame = fnew == read(ffile, String)
        println("gen_atoms: src/pl-atom.jl ", same ? "matches" : "DIFFERS from",
            " src/ATOMS @ $(commit[1:12])")
        println("gen_atoms: src/pl-funct.jl ", fsame ? "matches" : "DIFFERS from",
            " src/ATOMS @ $(commit[1:12])")
        exit(same && fsame ? 0 : 1)
    end
    write(file, new)
    write(ffile, fnew)
    println(
        "gen_atoms: wrote $(length(texts)) atoms and $(length(fs)) functors from src/ATOMS @ $(commit[1:12])"
    )
end
