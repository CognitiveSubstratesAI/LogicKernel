# NOT LISTED (equivalent, with the code reason):
#   * dropping the `ld.alerted &= ~ALERT_WAKEUP` of `check_wakeup` or of `exit_checking_wakeup`: a stale bit with an
#     empty list is harmless — every check point tests the head cell before it wakes (src/pl-wam.jl `check_wakeup`,
#     the block at `exit_checking_wakeup`) and `updateAlerted` recomputes it; only the fast path's saving is lost;
#   * dropping `ld.attvar_head != 0 &&` in `updateAlerted`: every engine's `emptyStacks` makes the head (the guard is
#     upstream's `stacks.local.base` test, for an engine without stacks, which this one never is);
#   * dropping the occurs-check trail walk's skip of the wakeup list's entries (src/pl-prims.jl): the entries come in
#     address/value PAIRS, so the walk stays aligned and checks the head and tail cells as two more "bindings" — a
#     cell holding a compound or [] whose variable (itself) does not occur in it: no answer changes. (The skip is
#     upstream's saving; a skip that goes TOO FAR is the mutant P3.);
#   * `updateAlerted` at `PL_open_query` / `restore_after_query` (src/pl-wam.jl): the same stale-bit argument.
# The `old` strings were written BEFORE `tools/warm.sh fmt`: re-check them after it (mutate_drive.py refuses a string
# that does not occur exactly once).
