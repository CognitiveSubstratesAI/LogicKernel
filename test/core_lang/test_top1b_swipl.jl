# the events swipl 10.1.19 gives (filled by evidence/TOP1B/gen_top1b_rows.py): the scenario id, then its events joined by `,`
const _TB_PINNED = [
    # PINS-BEGIN
    "tb01 none",
    "tb02 lvl(0),lvl(1),lvl(2),lvl(1),lvl(0)",
    "tb03 m(informational,begin,1),m(informational,end,1)",
    "tb03n begin(1),begin(2),end(2),end(1)",
    "tb04 in(rowin),out(rowout),in(user_input),out(user_output),in(rowin),out(rowout)",
    "tb06a lvl(0),lvl(0)",
    "tb06b lvl(1),lvl(1)"
    # PINS-END
]

"The pin of scenario `id`: its events' encoding."
function _tb_pin(id::String)::Union{Nothing, String}
    for l in _TB_PINNED
        k, v = split(l, " "; limit=2)
        k == id && return String(v)
    end
    return nothing
end

const _TB_GOT = Dict{String, String}()      # scenario id -> the kernel's encoding, filled by `_tb_check`

"Compare the kernel's events of scenario `id` with swipl's pin (ONE encoder for both: the events joined by `,`)."
function _tb_check(id::String, evs::Vector{String})::Nothing
    pin = _tb_pin(id)
    @test pin !== nothing
    pin === nothing && return nothing
    enc = join(evs, ",")
    _TB_GOT[id] = enc
    @test enc == pin
    return nothing
end

"A database whose three user streams are buffers: `(db, (ui, uo, ue))`; `tp_ev/1` and `tp_seen/0` are dynamic in `user`."
function _tb_db(; booted::Bool)
    db = booted ? _RDB() : _RDB_unbooted()
    # the booted copy records the `informational` messages (break(begin|end, Level)) through a user:message_hook/3 collector
    booted && lk_install_message_collector!(db.gd, db.ld; kinds=(:informational,))
    db.gd.halt_exit = false
    ld = db.ld
    ui = LK.set_standard_stream!(ld, LK.SNO_USER_INPUT, IOBuffer())
    uo = LK.set_standard_stream!(ld, LK.SNO_USER_OUTPUT, IOBuffer())
    ue = LK.set_standard_stream!(ld, LK.SNO_USER_ERROR, IOBuffer())
    LK.setDynamicDefinition!(LK.lookupProcedure(_rs(:tp_ev), 1, db.user).definition, true)
    LK.setDynamicDefinition!(LK.lookupProcedure(_rs(:tp_seen), 0, db.user).definition, true)
    return db, (ui, uo, ue)
end

"`name :- body` (a fact for `body` nothing) in the module `system`: a goal `query_loop` runs."
function _tb_sys!(db::_RDB, name::Symbol, body::Union{Nothing, _R}=nothing)
    head = _rs(name)
    sys = LK.MODULE_system(db.gd)
    pr = LK.lookupProcedure(head, 0, sys)
    cl = LK.compileClause(db.gd, db.ld, head, body, pr, sys)
    LK.assertDefinition!(db.gd, pr.definition, cl, LK.CL_END)
    return nothing
end

"`assertz(user:tp_ev(t))`"
_tb_ev(t::_R) = _rf("assertz", _rf(":", _rs(:user), _rf("tp_ev", t)))
"`( current_prolog_flag(break_level, V) -> assertz(user:tp_ev(lvl(V))) ; assertz(user:tp_ev(none)) )`: variable `v` is the goal's own"
_tb_lvl(v::Int) = _rite(
    _rf("current_prolog_flag", _rs(:break_level), _rv(v)), _tb_ev(_rf("lvl", _rv(v))),
    _tb_ev(_rs(:none))
)
"`( user:tp_seen -> true ; assertz(user:tp_seen), throw(tp_ball) )`: raises the first time, succeeds the second"
_tb_once_raise() = _rite(
    _rf(":", _rs(:user), _rs(:tp_seen)), _rs(:true),
    _rconj(
        _rf("assertz", _rf(":", _rs(:user), _rs(:tp_seen))), _rf("throw", _rs(:tp_ball))
    )
)
"`current_input`/`current_output` named by their alias, recorded as `in(A)` and `out(B)` (`none` where the stream has no alias)"
_tb_streams_goal() = _rconj(
    _rf("current_input", _rv(1)),
    _rite(
        _rf("stream_property", _rv(1), _rf("alias", _rv(2))),
        _rs(:true),
        _rf("=", _rv(2), _rs(:none))
    ),
    _tb_ev(_rf("in", _rv(2))),
    _rf("current_output", _rv(3)),
    _rite(
        _rf("stream_property", _rv(3), _rf("alias", _rv(4))),
        _rs(:true),
        _rf("=", _rv(4), _rs(:none))
    ),
    _tb_ev(_rf("out", _rv(4)))
)

"The events the goals recorded (`user:tp_ev/1`), in order, as the text of the argument: `lvl(0)`, `none`, …"
function _tb_events(db::_RDB)::Vector{String}
    out = String[]
    for (a, _) in _rcall(db, _rf("tp_ev", _rv(1)))
        @assert startswith(a, "tp_ev(") && endswith(a, ")") a
        push!(out, chop(a; head=6, tail=1))
    end
    return out
end

"""
The `break(begin|end, Level)` messages printed so far: from the message_hook collector (`m(kind,begin,1)`, a BOOTED copy) when `kinds`, else
from the fallback branch of `printMessage` on `ld.messages` (the term only: `begin(1)`, the UNBOOTED copy).
"""
function _tb_breaks(ld::LK.PL_local_data{_R}; kinds::Bool)::Vector{String}
    terms = if kinds
        [(k, t) for (k, t) in lk_take_messages!(ld)]
    else
        [(k, t) for (k, t) in ld.messages]
    end
    out = String[]
    for (k, t) in terms
        m = match(r"^break\((begin|end),\s*(\d+)\)$", _rcanonical(t))
        m === nothing && continue
        push!(out, kinds ? "m($(k),$(m[1]),$(m[2]))" : "$(m[1])($(m[2]))")
    end
    return out
end

