"A `vm_list/1` line's instruction name: no label, no address, no operands."
_su_vm_name(l::String)::String =
    first(split(replace(replace(l, r"^\w+:\s+" => ""), r"^\d+\s+" => ""), '('))

@testset "the compiled code of SSU clauses == swipl's vm_list (v01-v10), by instruction name" begin
    f, names = _su_file()
    _, gd, _ = _su_kernel(f, String[])                   # the program only; no case runs
    for (name, arity, lines) in _SU_VM
        want = _su_vm_name.(lines[2:end])
        k = findfirst(==("i_chp"), want)::Int
        want_sv, want_cl = want[1:(k - 1)], want[k:end]
        def = _su_def(gd, name, arity)
        @test LK.setDefaultSupervisor(gd, def)           # what S_VIRGIN installs on the first call
        @test (name, _su_names(def.codes)) == (name, want_sv)
        got_cl = reduce(vcat, [_su_names(c.codes) for c in _su_clauses(def)])
        @test (name, got_cl) == (name, want_cl)
    end
    # not vacuous: the rows hold both necks, the merged voids (v04, v07: no h_void before i_ssu_*) and a move (v05)
    @test count(l -> endswith(l, "i_ssu_commit"), reduce(vcat, [x[3] for x in _SU_VM])) >= 8
    @test count(l -> endswith(l, "i_ssu_choice"), reduce(vcat, [x[3] for x in _SU_VM])) >= 6
end

# ---- KNOWN DIFFERENCE (checklist item: docs/architecture.md § "SSU1", pending the control-construct procedures): asserting a
# clause whose head is a control construct. swipl raises permission_error(modify, static_procedure, (',')/2) — `','/2` is a
# system procedure there; the kernel defines no `system:','/2` procedure (`isStaticSystemProcedure` finds none), so its assert
# path creates `user:','/2` and the assert succeeds: R stays unbound. Not an SSU gap: the plain `assertz((a, b))` (k01) differs
