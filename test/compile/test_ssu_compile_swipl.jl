"The program and cases as one file; the case predicates' names."
function _su_file()::Tuple{String, Vector{String}}
    names = ["t_$(id)" for (id, _) in _SU_CASES]
    text = _SU_PROGRAM * join(["t_$(id)(R) :- ($g).\n" for (id, g) in _SU_CASES])
    f = joinpath(mktempdir(), "ssu.pl")
    write(f, text)
    return f, names
end

"The kernel's lines for `names` after consulting `path`, as the driver writes swipl's; the database, for the white-box tests."
function _su_kernel(path::String, names::Vector{String})
    gd = LK.PL_global_data{_SU}()
    ld = LK.PL_local_data{_SU}(gd)
    st, ball, _ = LK.load_file!(gd, ld, path)
    out = [st === :ok ? "ok" : "exc " * _su_enc(ball::_SU)]
    for name in names
        proc = LK.isCurrentProcedure(sym_key(_sus(name)), 1, LK.MODULE_user(gd))
        if proc === nothing || !LK.isDefinedProcedure(gd, proc)
            push!(out, "$name undefined")
            continue
        end
        sols = String[]
        fid = LK.PL_open_foreign_frame(ld)
        a = LK.PL_new_term_refs(ld, 1)
        LK.putSlotValue!(ld, a + 1, mk_var(_SU, LK.fresh_var_keys!(1)), LK.PutVarMap())
        qid = LK.PL_open_query(
            gd, ld, nothing, LK.PL_Q_CATCH_EXCEPTION | LK.PL_Q_EXT_STATUS, proc, a
        )
        n = 0
        while (n += 1) <= 50
            rc = LK.PL_next_solution(gd, ld, qid)
            if rc == LK.PL_S_TRUE || rc == LK.PL_S_LAST
                push!(
                    sols,
                    _su_enc(mk_expr(_SU, _SU[_sus(name), lk_answers(ld, (a:a)...)...]))
                )
                rc == LK.PL_S_LAST && break
            elseif rc == LK.PL_S_EXCEPTION
                push!(sols, "exception")
                break
            else
                break
            end
        end
        LK.PL_close_query(ld, qid)
        LK.PL_close_foreign_frame(ld, fid)
        push!(out, "$name" * join(" " .* sols))
    end
    return out, gd, ld
end

"The definition of `name/arity` in `user`."
_su_def(gd, name::String, arity::Int) =
    (
        LK.isCurrentProcedure(
            sym_key(_sus(name)), arity, LK.MODULE_user(gd)
        )::LK.Procedure{_SU}
    ).definition

"The definition's clauses, in order."
function _su_clauses(def)::Vector{LK.Clause{_SU}}
    out = LK.Clause{_SU}[]
    cref = def.impl_clauses.first_clause
    while cref !== nothing
        push!(out, cref.clause::LK.Clause{_SU})
        cref = cref.next
    end
    return out
end

"The instruction names of a code vector, as swipl's `vm_list/1` names them (operands stepped over)."
function _su_names(codes::Vector{UInt64})::Vector{String}
    out = String[]
    pc = 1
    while pc <= length(codes)
        info = LK.codeTable(codes[pc])
        push!(out, lowercase(String(info.name)))
        pc += 1 + info.arguments
    end
    return out
end

@testset "SSU clauses compile, assert, decompile and are listed by '\$rule'/2 == swipl 10.1.19" begin
    f, names = _su_file()
    kl, gd, ld = _su_kernel(f, names)
    @test length(_SU_PINNED) == length(names) + 1 && _SU_PINNED[1] == "ok"     # the pins cover every case
    @test kl == _SU_PINNED
    # not a vacuous agreement: each kind of answer is in the pins (one extractor: `count` on them)
    @test count(l -> occursin("c[61,62]/2(", l), _SU_PINNED) >= 8              # `=>` terms ('$rule'/2)
    @test count(l -> occursin("c[63,61,62]/2(", l), _SU_PINNED) >= 5           # `?=>` terms
    @test count(l -> occursin("c[112,101,114,109", l), _SU_PINNED) == 2       # permission_error: a02, a03
    @test count(l -> l in ("t_a10", "t_a11", "t_a12"), _SU_PINNED) == 3        # retract fails on every neck
    # a14/a15 (ssu_rows.out: 1 and 1): a refused assert left nothing behind (H6)
    @test _su_def(gd, "d2", 1).impl_clauses.number_of_clauses == 1
    @test _su_def(gd, "d3", 1).impl_clauses.number_of_clauses == 1
    # a06/a07/a08 (yes, yes, no) and c19 (1): the `ssu` attribute is P_SSU_DET
    @test (_su_def(gd, "m", 2).flags & LK.P_SSU_DET) != 0
    @test (_su_def(gd, "nd", 1).flags & LK.P_SSU_DET) != 0
    @test (_su_def(gd, "t_c01", 1).flags & LK.P_SSU_DET) == 0
    @test (_su_def(gd, "d2", 1).flags & LK.P_SSU_DET) != 0                     # the first clause decided
    @test (_su_def(gd, "d3", 1).flags & LK.P_SSU_DET) == 0
    # c21 (1): an SSU clause with body `true` is a rule, not a UNIT_CLAUSE
    zero = _su_def(gd, "zero", 0)
    @test zero.impl_clauses.number_of_rules == 1 && zero.impl_clauses.number_of_clauses == 1
    # the clause flags (pl-comp.c:2028): the neck, and the guard form stored as ?=> (D7)
    @test [c.flags & LK.CLAUSE_TYPE_MASK for c in _su_clauses(_su_def(gd, "m", 2))] ==
        [LK.SSU_COMMIT_CLAUSE, LK.SSU_COMMIT_CLAUSE]
    @test [c.flags & LK.CLAUSE_TYPE_MASK for c in _su_clauses(_su_def(gd, "nd", 1))] ==
        [LK.SSU_CHOICE_CLAUSE, LK.SSU_CHOICE_CLAUSE]
    @test [c.flags & LK.CLAUSE_TYPE_MASK for c in _su_clauses(_su_def(gd, "sign", 2))] ==
        [LK.SSU_CHOICE_CLAUSE, LK.SSU_CHOICE_CLAUSE, LK.SSU_COMMIT_CLAUSE]
    @test [c.flags & LK.CLAUSE_TYPE_MASK for c in _su_clauses(zero)] ==
        [LK.SSU_COMMIT_CLAUSE]
    @test [c.flags & LK.CLAUSE_TYPE_MASK for c in _su_clauses(_su_def(gd, "ht2", 2))] ==
        [LK.UNIT_CLAUSE]
end

