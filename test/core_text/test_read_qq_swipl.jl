"The program and cases as one file (in `dir`); the case predicates' names."
function _qq_file(dir::String, program::String, cases)::Tuple{String, Vector{String}}
    names = ["t_$(id)" for (id, _) in cases]
    text =
        replace(program, "@RTDIR@" => dir) * join([
            "t_$(id)(R) :- catch(($g), error(SsuE, _), R = raised(SsuE)).\n" for
            (id, g) in cases
        ])
    f = joinpath(dir, "rd2.pl")
    write(f, text)
    return f, names
end
"The kernel's lines for `names` after consulting `path`, as the driver writes swipl's. A Julia exception out of a row is its line: `jlerr <type> <what>`."
function _qq_kernel(path::String, names::Vector{String})
    gd = LK.PL_global_data{_QQ}()
    ld = LK.PL_local_data{_QQ}(gd)
    st, ball = LK.load_file!(gd, ld, path)
    out = [st === :ok ? "ok" : "exc " * _qq_enc(ball::_QQ)]
    for name in names
        proc = LK.isCurrentProcedure(sym_key(_qqs(name)), 1, LK.MODULE_user(gd))
        if proc === nothing || !LK.isDefinedProcedure(gd, proc)
            push!(out, "$name undefined")
            continue
        end
        sols = String[]
        rld = LK.PL_local_data{_QQ}(gd)        # a fresh engine per row: a Julia exception leaves no frame behind
        try
            fid = LK.PL_open_foreign_frame(rld)
            a = LK.PL_new_term_refs(rld, 1)
            LK.putSlotValue!(rld, a + 1, mk_var(_QQ, LK.fresh_var_keys!(1)), LK.PutVarMap())
            qid = LK.PL_open_query(
                gd, rld, nothing, LK.PL_Q_CATCH_EXCEPTION | LK.PL_Q_EXT_STATUS, proc, a
            )
            n = 0
            while (n += 1) <= 50
                rc = LK.PL_next_solution(gd, rld, qid)
                if rc == LK.PL_S_TRUE || rc == LK.PL_S_LAST
                    push!(
                        sols,
                        _qq_enc(
                            mk_expr(_QQ, _QQ[_qqs(name), lk_answers(rld, (a:a)...)...])
                        )
                    )
                    rc == LK.PL_S_LAST && break
                elseif rc == LK.PL_S_EXCEPTION
                    push!(sols, "exception")
                    break
                else
                    break
                end
            end
            LK.PL_close_query(rld, qid)
            LK.PL_close_foreign_frame(rld, fid)
        catch e
            sols = [
                "jlerr $(nameof(typeof(e)))" * (e isa LK.NotPortedError ? " $(e.what)" : "")
            ]
        end
        push!(out, "$name" * join(" " .* sols))
    end
    return out
end



@testset "the quasi_quotations(Q) option, the syntax errors, the positions, streams, the flag and \$qq_open/2 as swipl's (qa01-qa97)" begin
    mktempdir() do dir
        f, names = _qq_file(dir, _QQ_HELPERS, _QQA_CASES)
        kl = _qq_kernel(f, names)
        @test length(kl) == length(_QQA_PINNED)
