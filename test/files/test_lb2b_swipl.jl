# ORIGINAL: a differential of LB2b's file predicates (os/pl-files.c, os/pl-glob.c) against swipl at the pin
# test/files/test_lb2b_swipl.jl — time_file/2, size_file/2, access_file/2, read_link/3, exists_file/1, exists_directory/1,
# is_absolute_file_name/1, same_file/2, file_base_name/2, file_directory_name/2, file_name_extension/3, prolog_to_os_filename/2,
# make_directory/1, delete_directory/1, rename_file/2, `$absolute_file_name`/2, `$cwd`/1, `$chdir`/1, `$mark_executable`/1,
# `$my_file`/1, wildcard_match/2,3, expand_file_name/2 and directory_files/2, through a PROGRAM (the pattern of
# test/core_lang/test_sys_swipl.jl): test_lb2b_swipl.pl holds the rows (generated by evidence/LB2B/gen_lb2b_rows.py), each a
# predicate `tN(R)`; the kernel consults it and enumerates every solution of every tN/1, and its lines are compared with
# test_lb2b_swipl.out — swipl 10.1.19's own (evidence/LB2B/run_lb2b_rows.sh: two byte-identical runs, `timeout 20`). When
# `swipl` is on PATH the .out is checked against a live run as well, so it cannot go stale.
# The rows work on the files lk_lb2b_* the test makes in a fresh directory, and are independent of its absolute path
# (an absolute answer is cut at the working directory); the mutating rows (mkdir, rmdir, rename, chmod) come last.
# tmp_file/2, `$tmp_file_stream`/4 and the IRI arguments (`http://...`) are refused by name: checked as refusals below.
# UNVERIFIED on the kernel: gate decides
