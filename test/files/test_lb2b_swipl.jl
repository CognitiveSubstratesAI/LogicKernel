const LK = LogicKernel

# TERM TYPES PER CHUNK: REFERENCE — built on the term layer; every type in CI and at milestones
include(joinpath(@__DIR__, "..", "term_under_test.jl"))
const _TL = lk_term_type(Union{Int64, Float64, String, BigInt, Rational{BigInt}})
_tls(x) = lk_sym(_TL, Symbol(x))

_codes(s::String) = "[" * join(Int.(collect(s)), ",") * "]"
function enc(t::_TL, seen::Vector{UInt64}=UInt64[])::String
    k = kind(t)
    if k === VAR
        i = findfirst(==(var_key(t)), seen)
        if i === nothing
            push!(seen, var_key(t))
            i = length(seen)
        end
        return "V$(i - 1)"
    elseif k === SYM
        return is_nil(t) ? "nil" : "a" * _codes(sym_text(t))
    elseif k === GND
        v = lk_value(t)
        v isa AbstractString && return "s" * _codes(String(v))
        v isa Integer && return "i$v"
        v isa Rational && return "q$(numerator(v))r$(denominator(v))"
        v isa AbstractFloat && return "f$(v)"
        return "?$(typeof(v))"
    end
    h = child(t, 1)
    return (is_nil(h) ? "c[]" : "c" * _codes(sym_text(h))) * "/$(nchildren(t) - 1)(" *
           join([enc(child(t, i), seen) for i in 2:nchildren(t)], ",") * ")"
end

const _LB2B_PL = joinpath(@__DIR__, "test_lb2b_swipl.pl")
const _LB2B_OUT = joinpath(@__DIR__, "test_lb2b_swipl.out")

# the rows' names, in the order of the program
_lb2b_names() =
    unique([String(m[1]) for m in eachmatch(r"^(t\d+)\(R\) :-"m, read(_LB2B_PL, String))])

# the fixtures the rows work on, in the current directory (evidence/LB2B/fixtures.sh makes the same)
function _lb2b_fixtures()
    write("lk_lb2b_file", "hello")
    for f in ("lk_lb2b_file.txt", "lk_lb2b_other.txt", "lk_lb2b_other.pl", "lk_lb2b_x.pl")
        write(f, "")
    end
    mkdir("lk_lb2b_dir")
    mkdir(joinpath("lk_lb2b_dir", "sub"))
    for f in ("a1.txt", "b2.txt", ".hidden", joinpath("sub", "deep.txt"))
        write(joinpath("lk_lb2b_dir", f), "")
    end
    symlink("lk_lb2b_file", "lk_lb2b_link")
    symlink("lk_lb2b_dir", "lk_lb2b_dlink")
    symlink("lk_lb2b_nowhere", "lk_lb2b_dangling")
    symlink("lk_lb2b_loop2", "lk_lb2b_loop1")
    symlink("lk_lb2b_loop1", "lk_lb2b_loop2")
    write("lk_lb2b_exec", "")
    chmod("lk_lb2b_exec", 0o755)
    write("lk_lb2b_ro", "")
    chmod("lk_lb2b_ro", 0o444)
    for f in ("lk_lb2b_r1", "lk_lb2b_r2", "lk_lb2b_r3", "lk_lb2b_r4", "lk_lb2b_m1")
        write(f, "")
    end
    mkdir("lk_lb2b_rd1")
    mkdir("lk_lb2b_gs")                                       # LB2B-E4: two directories whose names differ at `.`/`/`
    mkdir("lk_lb2b_gs.d")
    write(joinpath("lk_lb2b_gs", "f1"), "")
    write(joinpath("lk_lb2b_gs.d", "f1"), "")
    return nothing
end

# run `f` in a fresh directory that holds the fixtures; the directory is removed afterwards
function _in_fixture_dir(f::Function)
    return mktempdir() do d
        cd(d) do
            _lb2b_fixtures()
            f(d)
        end
    end
end

# the solutions of the row `name`/1, as `enc` lines (a Julia exception, a refusal included, is not caught here)
function _lb2b_row(gd, ld, name::String)::Vector{String}
    proc = LK.isCurrentProcedure(sym_key(_tls(name)), 1, LK.MODULE_user(gd))
    if proc === nothing || !LK.isDefinedProcedure(gd, proc)
        return String["$name undefined"]
    end
    sols = String[]
    fid = LK.PL_open_foreign_frame(ld)
    a = LK.PL_new_term_refs(ld, 1)
    pvm = LK.PutVarMap()
    LK.putSlotValue!(ld, a + 1, mk_var(_TL, LK.fresh_var_keys!(1)), pvm)
    qid = LK.PL_open_query(
        gd, ld, nothing, LK.PL_Q_CATCH_EXCEPTION | LK.PL_Q_EXT_STATUS, proc, a
    )
    try
        n = 0
        while (n += 1) <= 100
            rc = LK.PL_next_solution(gd, ld, qid)
            if rc == LK.PL_S_TRUE || rc == LK.PL_S_LAST
                push!(
                    sols,
                    try
                        enc(mk_expr(_TL, _TL[_tls(name), lk_answers(ld, (a:a)...)...]))
                    catch e
                        "export-error " * first(sprint(showerror, e), 80)
                    end
                )
                rc == LK.PL_S_LAST && break
            elseif rc == LK.PL_S_EXCEPTION
                push!(sols, "exception")
                break
            else
                break
            end
        end
    finally
        LK.PL_close_query(ld, qid)
        LK.PL_close_foreign_frame(ld, fid)
    end
    return String["$name" * join(" " .* sols)]
end

# the kernel's lines: `ok` (the program loaded), then each row's name and solutions
function kernel_lines(path::String, names::Vector{String})::Vector{String}
    gd = LK.PL_global_data{_TL}()
    ld = LK.PL_local_data{_TL}(gd)
    st, ball = LK.load_file!(gd, ld, path)
    out = [st === :ok ? "ok" : "exc " * enc(ball::_TL)]
    for name in names
        append!(out, _lb2b_row(gd, ld, name))
    end
    return out
end

# the driver swipl runs to print its lines (the .out is its output)
const DRIVER = raw"""
enc(T) :- enc(T, [], _).
enc(V, S0, S) :- var(V), !, ( vidx(S0, V, 0, I) -> S = S0 ; length(S0, I), append(S0, [V], S) ), format("V~w", [I]).
enc(T, S, S) :- T == [], !, write(nil).
enc(T, S, S) :- atom(T), !, atom_codes(T, Cs), format("a~w", [Cs]).
enc(T, S, S) :- string(T), !, string_codes(T, Cs), format("s~w", [Cs]).
enc(T, S, S) :- integer(T), !, format("i~w", [T]).
enc(T, S, S) :- rational(T, N, D), !, format("q~wr~w", [N, D]).
enc(T, S, S) :- float(T), !, format("f~w", [T]).
enc(T, S0, S) :- compound_name_arity(T, N, A),
    ( N == [] -> write('c[]') ; atom_codes(N, Cs), format("c~w", [Cs]) ),
    format("/~w(", [A]), encargs(1, A, T, S0, S), write(')').
encargs(I, A, _, S, S) :- I > A, !.
encargs(I, A, T, S0, S) :- arg(I, T, X), enc(X, S0, S1), ( I < A -> write(',') ; true ),
    I1 is I+1, encargs(I1, A, T, S1, S).
vidx([X|_], V, I, I) :- X == V, !.
vidx([_|Xs], V, I0, I) :- I1 is I0+1, vidx(Xs, V, I1, I).
fz_pred(N) :-
    format("~w", [N]), functor(G, N, 1),
    catch(findnsols(100, G, G, Gs), _, Gs = [exception]),
    forall(member(S, Gs), ( S == exception -> write(' exception') ; write(' '), enc(S) )), nl.
fz_run(File, Ns) :-
    catch(( consult(File), S = ok ), E, S = exc(E)),
    ( S == ok -> writeln(ok) ; S = exc(B), write('exc '), enc(B), nl ),
    forall(member(N, Ns), fz_pred(N)).
"""
function swipl_lines(path::String, names::Vector{String})::Vector{String}
    out = mktempdir() do d
        f = joinpath(d, "drv.pl")
        write(
            f,
            DRIVER * ":- initialization((fz_run('$path', [" * join(names, ",") *
            "]), halt)).\n"
        )
        read(pipeline(`swipl -q $f`; stdin=devnull, stderr=devnull), String)
    end
    return String.(split(chomp(out), '\n'; keepempty=false))
end

# LB2B-E4 (white box): the sort of expand_file_name/2's answers, called on an UNSORTED vector of names. The order in which a
# directory's names come out of readdir is the file system's, so no row can be sure to see a missing sort: this one does not
# go through the file system. pl-glob.c sort_expand compares with strcmp (bytes): 'A' < 'a', a prefix before its extensions,
# and '-' (0x2D) < '.' (0x2E) < '/' (0x2F), so the names of two directories sort by the directory name, `/` last.
@testset "LB2b: sort_expand sorts the names expand found, bytewise (pl-glob.c sort_expand)" begin
    gd = LK.PL_global_data{_TL}()
    ld = LK.PL_local_data{_TL}(gd)
    unsorted = ["lk_b/f", "lk_a/f", "lk_a.d/f", "lk_a-b/f", "lk_a", "lk_A/f", "lk_"]
    sorted = ["lk_", "lk_A/f", "lk_a", "lk_a-b/f", "lk_a.d/f", "lk_a/f", "lk_b/f"]
    @test unsorted != sorted                                    # not vacuous: the input is out of order
    @test LK.sort_expand(ld, unsorted) == sorted
    @test LK.sort_expand(ld, reverse(sorted)) == sorted
    @test LK.sort_expand(ld, sorted) == sorted
    @test LK.sort_expand(ld, String[]) == String[]
end

@testset "LB2b: the file predicates == swipl's answers (the .out), through a program" begin
    names = _lb2b_names()
    expected = String.(readlines(_LB2B_OUT))
    # not a vacuous agreement: the .out has a line per row, and the rows' own evidence is in it
    @test length(names) >= 380
    @test length(expected) == length(names) + 1 && expected[1] == "ok"
    @test all(i -> startswith(expected[i + 1], names[i] * " "), eachindex(names))
    @test count(l -> occursin(_codes("existence_error"), l), expected) >= 25
    @test count(l -> occursin(_codes("No such file or directory"), l), expected) >= 8
    @test any(l -> occursin(_codes("permission_error"), l), expected)
    @test any(l -> occursin(_codes("domain_error"), l), expected)         # access_file/2's mode
    @test any(l -> occursin(_codes("type_error"), l), expected)
    @test any(l -> occursin(_codes("instantiation_error"), l), expected)
    @test any(l -> occursin(_codes("max_path_length"), l), expected)      # a name of 5000 characters
    @test any(l -> occursin(_codes("lk_lb2b_dir/a1.txt"), l), expected)   # expand_file_name's answers
    @test any(l -> occursin(_codes("too many")[1:(end - 1)], l), expected) # a symbolic link loop (the start of its message)
    @test count(l -> occursin("(a" * _codes("false") * ")", l), expected) >= 50   # (res/2) the rows that fail
    @test count(l -> occursin("(a" * _codes("true") * ")", l), expected) >= 60    # ... and succeed

    kl = _in_fixture_dir() do d
        lines = kernel_lines(_LB2B_PL, names)
        # the file system after the run, as the mutating rows leave it
        @test isdir("lk_lb2b_n1") == false && isdir("lk_lb2b_n3") && isdir("lk_lb2b_n4") &&
            isdir("lk_lb2b_rd2")
        @test isfile("lk_lb2b_r1b") && isfile("lk_lb2b_r3") && !isfile("lk_lb2b_r2")
        @test isfile("lk_lb2b_r4b") && !isfile("lk_lb2b_r4")
        @test (filemode("lk_lb2b_m1") & 0o111) != 0
        lines
    end
    @test length(kl) == length(expected)
    for i in eachindex(kl)
        @test (i, kl[i]) == (i, expected[i])
    end

    swipl = get(ENV, "LOGICKERNEL_NO_SWIPL", "") == "1" ? nothing : Sys.which("swipl")
    if swipl === nothing
        @info "LB2b DIFFERENTIAL NOT RUN LIVE: `swipl` is not on PATH here (the .out was checked). It runs in tools/run_tests.sh and CI."
    else
        sw = _in_fixture_dir(d -> swipl_lines(_LB2B_PL, names))
        @test sw == expected                                       # the .out is swipl's, still
    end
end

# the refusals by name: not swipl's answers (the Julia kernel has no function behind them), an explicit NotPortedError
@testset "LB2b: refused by name — tmp_file/2, \$tmp_file_stream/4, IRI arguments" begin
    refusal(goal::String) = mktempdir() do d
        path = joinpath(d, "r.pl")
        write(path, "t0(R) :- $goal, R = ok.\n")
        gd = LK.PL_global_data{_TL}()
        ld = LK.PL_local_data{_TL}(gd)
        st, _ = LK.load_file!(gd, ld, path)
        @test st === :ok
        try
            _lb2b_row(gd, ld, "t0")
            nothing
        catch e
            e isa LK.NotPortedError || rethrow()
            e.step
        end
    end
    @test refusal("tmp_file(lk_lb2b, _)") == "LB2b audit"
    @test refusal("'\$tmp_file_stream'(txt, utf8, _, _)") == "LB2b audit"
    @test refusal("exists_file('http://example.org/x')") == "LB4"
    @test refusal("exists_directory('http://example.org/x')") == "LB4"
    @test refusal("time_file('http://example.org/x', _)") == "LB4"
    @test refusal("size_file('http://example.org/x', _)") == "LB4"
    @test refusal("access_file('http://example.org/x', read)") == "LB4"
    # a name that is no IRI (one letter before `://`, or `:/`) is an ordinary file name
    @test refusal("exists_file('a://x')") === nothing
    @test refusal("exists_file('http:/x')") === nothing
end
