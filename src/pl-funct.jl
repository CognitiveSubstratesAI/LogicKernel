# PORT: pl-table.h pointerHashValue
"The bucket of word `p` in a table of `size` buckets (os/pl-table.h; `size` a power of 2)."
pointerHashValue(p::UInt64, size::Int)::Int =
    Int(((p >> LMASK_BITS) ⊻ (p >> (LMASK_BITS + 5)) ⊻ p) & UInt64(size - 1))

# PORT: pl-funct.c allocateFunctorBlock
# DIVERGES: block `idx` is `array[idx + 1]`, indexed from 1 (see `fetchFunctorArray`).
"Allocate block `idx` of the functor array (pl-funct.c): `2^idx` empty entries."
function allocateFunctorBlock(functors::functors_t, idx::Int)::Nothing
    if functors.array[idx + 1] === nothing
        functors.array[idx + 1] = Union{Nothing, functorDef}[nothing for _ in 1:(1 << idx)]
    end
    return nothing
end

# PORT: pl-funct.c registerFunctor
"Give `fd` the next index and its word (pl-funct.c): arity inline up to `F_ARITY_MASK`, else the table's."
function registerFunctor(functors::functors_t, fd::functorDef)::Nothing
    functors.highest += 1                               # ATOMIC_INC(&GD->functors.highest) - 1
    index = functors.highest - 1
    idx = MSB(index)
    functors.array[idx + 1] === nothing && allocateFunctorBlock(functors, idx)
    amask = fd.arity < F_ARITY_MASK ? UInt64(fd.arity) : F_ARITY_MASK
    fd.functor = MK_FUNCTOR(UInt64(index), amask)
    (functors.array[idx + 1]::Vector{Union{Nothing, functorDef}})[index - (1 << idx) + 1] =
        fd
    fd.flags |= VALID_F
    return nothing
end

# PORT: pl-funct.c lookupFunctorDef
# DIVERGES: single-threaded (see the file header). NOT PORTED: `PL_register_atom(atom)` (AGC).
"The functor word of `atom/arity` (pl-funct.c), created if new; `atom` is an atom word."
function lookupFunctorDef(functors::functors_t, atom::UInt64, arity::Int)::UInt64
    table, buckets = functors.table.table, functors.table.buckets     # acquire_functor_table
    v = pointerHashValue(atom, buckets) + 1
    f = table[v]
    while f !== nothing
        if atom == f.name && f.arity == arity
            @assert FUNCTOR_IS_VALID(f.flags)           # !FUNCTOR_IS_VALID: goto redo (threads)
            return f.functor
        end
        f = f.next
    end
    if functors.table.buckets * 2 < functors.statistics_functors
        rehashFunctors(functors)
        table = functors.table.table                    # goto redo: the new table
        v = pointerHashValue(atom, functors.table.buckets) + 1
    end
    f = functorDef(table[v], UInt64(0), atom, arity, UInt32(0))
    table[v] = f                                        # COMPARE_AND_SWAP_PTR
    registerFunctor(functors, f)
    functors.statistics_functors += 1
    return f.functor
end

# PORT: pl-funct.c rehashFunctors
# DIVERGES: no previous table is kept (`newtab->prev`, `maybe_free_functor_tables`).
"Double the functor hash table and re-chain every valid functor (pl-funct.c)."
function rehashFunctors(functors::functors_t)::Nothing
    functors.table.buckets * 2 >= functors.statistics_functors && return nothing
    newtab = functor_table(
        functors.table.buckets * 2,
        Union{Nothing, functorDef}[nothing for _ in 1:(functors.table.buckets * 2)]
    )
    functors.rehashing = true
    index = 1
    i = 0
    last = false
    while !last
        upto = 2 << i
        b = functors.array[i + 1]
        if b !== nothing
            high = functors.highest
            if upto >= high
                upto = high
                last = true
            end
            while index < upto
                f = b[index - (1 << i) + 1]
                if f !== nothing && FUNCTOR_IS_VALID(f.flags)
                    v = pointerHashValue(f.name, newtab.buckets) + 1
                    f.next = newtab.table[v]
                    newtab.table[v] = f
                end
                index += 1
            end
        end
        i += 1
    end
    functors.table = newtab
    functors.rehashing = false
    return nothing
end

# PORT: pl-funct.c isCurrentFunctor
"The functor word of `atom/arity` if it exists, else 0 (pl-funct.c): it is never created."
function isCurrentFunctor(functors::functors_t, atom::UInt64, arity::Int)::UInt64
    rc = UInt64(0)
    f = functors.table.table[pointerHashValue(atom, functors.table.buckets) + 1]
    while f !== nothing
        if FUNCTOR_IS_VALID(f.flags) && atom == f.name && f.arity == arity
            rc = f.functor
            break
        end
        f = f.next
    end
    if rc == 0 && functors.table.buckets * 2 < functors.statistics_functors
        rehashFunctors(functors)
    end
    return rc
end

# PORT: pl-funct.c allocFunctorTable
"The empty functor hash table, `FUNCTORHASHSIZE` buckets (pl-funct.c)."
function allocFunctorTable(functors::functors_t)::Nothing
    functors.table = functor_table(
        FUNCTORHASHSIZE, Union{Nothing, functorDef}[nothing for _ in 1:FUNCTORHASHSIZE]
    )
    return nothing
end

# PORT: pl-funct.c registerBuiltinFunctors
# DIVERGES: the built-ins are the generated `_BUILTIN_FUNCTORS` (upstream: the static `functors[]`
# of pl-funct.ic), each named by its atom's index.
"Register the built-in functors in index order (pl-funct.c)."
function registerBuiltinFunctors(functors::functors_t)::Nothing
    functors.statistics_functors = length(_BUILTIN_FUNCTORS)
    for (a, arity) in _BUILTIN_FUNCTORS
        name = (UInt64(a) << LMASK_BITS) | TAG_ATOM
        v = pointerHashValue(name, functors.table.buckets) + 1
        f = functorDef(functors.table.table[v], UInt64(0), name, arity, UInt32(0))
        functors.table.table[v] = f
        registerFunctor(functors, f)
    end
    return nothing
end

# ORIGINAL: `FUNCTOR_<id><arity>` of the generated pl-funct.ih, by the name's atom id and the arity.
"The word of the built-in functor `FUNCTOR_<id><arity>` (pl-funct.ih)."
function builtin_functor(id::AbstractString, arity::Int)::UInt64
    a = findfirst(==(id), _BUILTIN_ATOM_IDS)
    k = a === nothing ? nothing : findfirst(==((a, arity)), _BUILTIN_FUNCTORS)
    k === nothing && throw(ArgumentError("no built-in functor FUNCTOR_$id$arity"))
    return MK_FUNCTOR(UInt64(k), arity < F_ARITY_MASK ? UInt64(arity) : F_ARITY_MASK)
end

# PORT: pl-funct.c registerControlFunctors
# DIVERGES: on one database's table; `O_CALL_AT_MODULE` is defined (pl-incl.h:236), so `@/2` is
# one. The compiler reads `ControlFunctors` (above) until stage C.
"Flag the control structures `CONTROL_F` on the table's definitions (pl-funct.c)."
function registerControlFunctors!(functors::functors_t)::Nothing
    for (id, n) in (
        ("comma", 2), ("semicolon", 2), ("bar", 2), ("ifthen", 2), ("softcut", 2),
        ("not_provable", 1), ("colon", 2), ("dollar", 1), ("at_sign", 2)
    )
        valueFunctor(functors, builtin_functor(id, n)).flags |= CONTROL_F
    end
    return nothing
end

# PORT: pl-funct.c registerArithFunctors
# DIVERGES: on one database's table. The compiler reads `_arith_functors` (above) until stage C.
"Flag the arithmetic comparisons and `is/2` `ARITH_F` on the table's definitions (pl-funct.c)."
function registerArithFunctors!(functors::functors_t)::Nothing
    for id in
        ("ar_equals", "ar_not_equal", "smaller", "larger", "smaller_equal", "larger_equal",
        "is")
        valueFunctor(functors, builtin_functor(id, 2)).flags |= ARITH_F
    end
    return nothing
end

# PORT: pl-funct.c initFunctors
# DIVERGES: once per database, on its own table, after its atom table (`initAtoms` is the caller's:
# `PL_global_data` builds `atoms` first); no `L_FUNCTOR` lock.
"Initialise the functor table (pl-funct.c): the hash table, the built-ins, their flags."
function initFunctors!(functors::functors_t)::functors_t
    if functors.table.buckets == 0                      # !functorDefTable
        allocFunctorTable(functors)
        functors.highest = 1
        registerBuiltinFunctors(functors)
        registerControlFunctors!(functors)
        registerArithFunctors!(functors)
    end
    return functors
end
