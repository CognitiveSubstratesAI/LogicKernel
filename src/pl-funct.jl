# PORT: pl-table.h pointerHashValue
"The bucket of word `p` in a table of `size` buckets (os/pl-table.h; `size` a power of 2)."
pointerHashValue(p::UInt64, size::Int)::Int =
    Int(((p >> LMASK_BITS) ⊻ (p >> (LMASK_BITS + 5)) ⊻ p) & UInt64(size - 1))

# PORT: pl-funct.c allocateFunctorBlock
# DIVERGES: block `idx` is `array[idx + 1]`, indexed from 1 (see `fetchFunctorArray`).
"Allocate block `idx` of the functor array (pl-funct.c): `2^idx` empty entries."
function allocateFunctorBlock(functors::functors_t, idx::Int)::Nothing
    if functors.array[idx + 1] === nothing
        functors.array[idx + 1] = Union{Nothing, functorDef}[nothing for _ in 1:(1 << idx)]
    end
    return nothing
end

# PORT: pl-funct.c addFunctorToArray
# (named `registerFunctor` until pl-funct.c at 8783a5bd renamed it)
"Give `fd` the next index and its word (pl-funct.c): arity inline up to `F_ARITY_MASK`, else the table's."
function addFunctorToArray(functors::functors_t, fd::functorDef)::Nothing
    functors.highest += 1                               # ATOMIC_INC(&GD->functors.highest) - 1
    index = functors.highest - 1
    idx = MSB(index)
    functors.array[idx + 1] === nothing && allocateFunctorBlock(functors, idx)
    amask = fd.arity < F_ARITY_MASK ? UInt64(fd.arity) : F_ARITY_MASK
    fd.functor = MK_FUNCTOR(UInt64(index), amask)
    (functors.array[idx + 1]::Vector{Union{Nothing, functorDef}})[index - (1 << idx) + 1] =
        fd
    fd.flags |= VALID_F
    return nothing
end

# PORT: pl-funct.c find_functor
# DIVERGES: single-threaded (see the file header): `acquire_functor_table` and `release_functor_table` are the table read.
"The valid functor `atom/arity` in the table, or `nothing` (pl-funct.c: the lock-free lookup)."
function find_functor(
    functors::functors_t, atom::UInt64, arity::Int
)::Union{Nothing, functorDef}
    table, buckets = functors.table.table, functors.table.buckets     # acquire_functor_table
    v = pointerHashValue(atom, buckets) + 1
    f = table[v]
    while f !== nothing
        if atom == f.name && f.arity == arity && FUNCTOR_IS_VALID(f.flags)
            return f
        end
        f = f.next
    end
    return nothing
end

# PORT: pl-funct.c find_functor_locked
# DIVERGES: no `L_FUNCTOR` (no threads).
"The functor `atom/arity` in the current table, or `nothing`; the caller holds `L_FUNCTOR` upstream (pl-funct.c)."
function find_functor_locked(
    functors::functors_t, atom::UInt64, arity::Int
)::Union{Nothing, functorDef}
    t = functors.table
    f = t.table[pointerHashValue(atom, t.buckets) + 1]
    while f !== nothing
        atom == f.name && f.arity == arity && return f
        f = f.next
    end
    return nothing
end

# PORT: pl-funct.c is_live_functor
"True if `f`, found by a lookup, is the live functor `atom/arity` (pl-funct.c)."
is_live_functor(f::functorDef, atom::UInt64, arity::Int)::Bool =
    (f.references & FUNCTOR_DESTROY_REF) == 0 && FUNCTOR_IS_VALID(f.flags) &&
    f.name == atom && f.arity == arity

# PORT: pl-funct.c create_functor
# DIVERGES: single-threaded (no `L_FUNCTOR`, no memory barriers). NOT PORTED: `PL_register_atom(atom)` (AGC, held).
# The branch that reuses a collected functor (`GD->functors.free`) is ported, though nothing is collected yet.
"Create the functor `atom/arity` with `refs` in its `references`; it is known not to exist (pl-funct.c)."
function create_functor(
    functors::functors_t, atom::UInt64, arity::Int, refs::UInt32
)::functorDef
    if functors.table.buckets * 2 < functors.statistics_functors
        rehashFunctors(functors)
    end
    t = functors.table
    v = pointerHashValue(atom, t.buckets) + 1
    f = functors.free
    if f !== nothing                                    # reuse a collected functor
        amask = arity < F_ARITY_MASK ? UInt64(arity) : F_ARITY_MASK
        functors.free = f.next_free
        f.next_free = nothing
        f.name = atom
        f.arity = arity
        f.references = refs
        f.functor = MK_FUNCTOR(UInt64(indexFunctor(f.functor)), amask)
        f.next = t.table[v]
        f.flags = VALID_F
    else
        f = functorDef(t.table[v], UInt64(0), atom, arity, UInt32(0), refs, nothing)
        addFunctorToArray(functors, f)
    end
    t.table[v] = f                                      # publish complete functor
    functors.statistics_functors += 1                   # ATOMIC_INC(&GD->statistics.functors)
    return f
end

# PORT: pl-funct.c lookupFunctorDef
# DIVERGES: single-threaded (see the file header). NOT PORTED: `PL_register_atom(atom)` (AGC, held; in `create_functor`).
"The permanent functor word of `atom/arity` (pl-funct.c), created if new; `atom` is an atom word."
function lookupFunctorDef(functors::functors_t, atom::UInt64, arity::Int)::UInt64
    f = find_functor(functors, atom, arity)
    if f !== nothing
        ref = f.references
        (ref & FUNCTOR_PERMANENT_REF) != 0 && return f.functor   # permanent functors are never collected nor reused
        f.references |= FUNCTOR_PERMANENT_REF                    # ATOMIC_OR
        is_live_functor(f, atom, arity) && return f.functor
    end
    # PL_LOCK(L_FUNCTOR)
    f = find_functor_locked(functors, atom, arity)
    if f !== nothing
        f.references |= FUNCTOR_PERMANENT_REF
    else
        f = create_functor(functors, atom, arity, FUNCTOR_PERMANENT_REF)
    end
    return f.functor
end

# PORT: pl-funct.c lookupFunctorRef
# DIVERGES: single-threaded: `COMPARE_AND_SWAP_UINT(&f->references, ref, nref)` always succeeds.
"The functor word of `atom/arity` with a counted reference added (pl-funct.c: `PL_new_functor()`); release it with `releaseFunctor`."
function lookupFunctorRef(functors::functors_t, atom::UInt64, arity::Int)::UInt64
    f = find_functor(functors, atom, arity)
    if f !== nothing
        while true
            ref = f.references
            if (ref & FUNCTOR_PERMANENT_REF) != 0
                if f.name == atom && f.arity == arity && FUNCTOR_IS_VALID(f.flags)
                    return f.functor                    # permanent: never reused
                end
                break
            end
            (ref & FUNCTOR_DESTROY_REF) != 0 && break
            nref = ref + UInt32(1)
            if FUNCTOR_REF_COUNT(nref) >= FUNCTOR_REF_SATURATED
                nref |= FUNCTOR_PERMANENT_REF
            end
            f.references = nref                         # COMPARE_AND_SWAP_UINT
            if f.name == atom && f.arity == arity && FUNCTOR_IS_VALID(f.flags)
                return f.functor
            end
            releaseFunctor(functors, f.functor)         # collected and reused
            break
        end
    end
    # PL_LOCK(L_FUNCTOR): collectFunctors() holds this
    f = find_functor_locked(functors, atom, arity)
    if f !== nothing
        acquireFunctor(functors, f.functor)
    else
        f = create_functor(functors, atom, arity, UInt32(1))
    end
    return f.functor
end

# PORT: pl-funct.c lookupVolatileFunctor
# DIVERGES (SYNC3, held with pl-atom/pl-gc): upstream protects the functor as `LD->atoms.volatile_functor`
# (`publish_volatile_functor`, which also marks it while AGC is active) and calls `considerFunctorGC` after
# creating one. Without atom GC and `collectFunctors` nothing collects a functor, so the hazard protocol has no
# reader: the functor is found or created with no reference and the protocol steps are left out. The caller
# keeps upstream's rule (store the functor in a term before the next call): the day the collector lands, the
# protocol steps go in here.
"The functor word of `atom/arity`, created if new, for building a term: it is not made permanent (pl-funct.c)."
function lookupVolatileFunctor(functors::functors_t, atom::UInt64, arity::Int)::UInt64
    f = find_functor(functors, atom, arity)
    if f !== nothing
        ft = f.functor
        (f.references & FUNCTOR_PERMANENT_REF) != 0 && return ft
        # LD->atoms.volatile_functor == ft: already protected; publish_volatile_functor(ft)   (held)
        is_live_functor(f, atom, arity) && f.functor == ft && return ft
    end
    # PL_LOCK(L_FUNCTOR)
    f = find_functor_locked(functors, atom, arity)
    if f === nothing
        f = create_functor(functors, atom, arity, UInt32(0))
        # considerFunctorGC()   (held)
    end
    # publish_volatile_functor(f->functor)   (held)
    return f.functor
end

# PORT: pl-funct.c permanentFunctor
# DIVERGES: no `GD->halt.cleaning == CLN_DATA` no-op: `cleanupFunctors` is not ported, so nothing frees functors
# while clauses and records are freed. The functor table, not `PL_global_data` (src/pl-global.jl comes after this
# file), is the argument.
"Make functor `f` permanent (pl-funct.c)."
function permanentFunctor(functors::functors_t, f::UInt64)::Nothing
    fd = valueFunctor(functors, f)
    if (fd.references & FUNCTOR_PERMANENT_REF) == 0
        fd.references |= FUNCTOR_PERMANENT_REF          # ATOMIC_OR
    end
    return nothing
end

# PORT: pl-funct.c acquireFunctor
# DIVERGES: as `permanentFunctor` (no CLN_DATA no-op).
"Add a counted reference to functor `f` (pl-funct.c); the caller has a reference from a term or another counted one."
function acquireFunctor(functors::functors_t, f::UInt64)::Nothing
    fd = valueFunctor(functors, f)
    if (fd.references & FUNCTOR_PERMANENT_REF) == 0
        fd.references += UInt32(1)                      # ATOMIC_INC: the new value
        if FUNCTOR_REF_COUNT(fd.references) >= FUNCTOR_REF_SATURATED
            fd.references |= FUNCTOR_PERMANENT_REF      # avoid overflow
        end
    end
    return nothing
end

# PORT: pl-funct.c releaseFunctor
# DIVERGES: as `permanentFunctor` (no CLN_DATA no-op); the `DEBUG(0, assert(count > 0))` is an `@assert`.
"Remove a counted reference from functor `f` (pl-funct.c)."
function releaseFunctor(functors::functors_t, f::UInt64)::Nothing
    fd = valueFunctor(functors, f)
    if (fd.references & FUNCTOR_PERMANENT_REF) == 0
        @assert FUNCTOR_REF_COUNT(fd.references) > 0
        fd.references -= UInt32(1)                      # ATOMIC_DEC
    end
    return nothing
end

# PORT: pl-funct.c rehashFunctors
# DIVERGES: no previous table is kept (`newtab->prev`, `maybe_free_functor_tables`).
"Double the functor hash table and re-chain every valid functor (pl-funct.c)."
function rehashFunctors(functors::functors_t)::Nothing
    functors.table.buckets * 2 >= functors.statistics_functors && return nothing
    newtab = functor_table(
        functors.table.buckets * 2,
        Union{Nothing, functorDef}[nothing for _ in 1:(functors.table.buckets * 2)]
    )
    index = 1
    i = 0
    last = false
    while !last
        upto = 2 << i
        b = functors.array[i + 1]
        if b !== nothing
            high = functors.highest
            if upto >= high
                upto = high
                last = true
            end
            while index < upto
                f = b[index - (1 << i) + 1]
                if f !== nothing && FUNCTOR_IS_VALID(f.flags)
                    v = pointerHashValue(f.name, newtab.buckets) + 1
                    f.next = newtab.table[v]
                    newtab.table[v] = f
                end
                index += 1
            end
        end
        i += 1
    end
    functors.table = newtab                             # MEMORY_RELEASE(): publish filled table
    return nothing
end

# PORT: pl-funct.c isCurrentFunctor
# DIVERGES: single-threaded: the second search (`find_functor_locked`, upstream's guard against a rehash in
# progress) finds nothing the first did not.
"The functor word of `atom/arity` if it exists, else 0 (pl-funct.c): it is never created."
function isCurrentFunctor(functors::functors_t, atom::UInt64, arity::Int)::UInt64
    f = find_functor(functors, atom, arity)
    if f !== nothing
        return f.functor
    end
    f = find_functor_locked(functors, atom, arity)          # we may miss it during a rehash
    return f === nothing ? UInt64(0) : f.functor
end

# PORT: pl-funct.c allocFunctorTable
"The empty functor hash table, `FUNCTORHASHSIZE` buckets (pl-funct.c)."
function allocFunctorTable(functors::functors_t)::Nothing
    functors.table = functor_table(
        FUNCTORHASHSIZE, Union{Nothing, functorDef}[nothing for _ in 1:FUNCTORHASHSIZE]
    )
    return nothing
end

# PORT: pl-funct.c registerBuiltinFunctors
# DIVERGES: the built-ins are the generated `_BUILTIN_FUNCTORS` (upstream: the static `functors[]`
# of pl-funct.ic), each named by its atom's index.
"Register the built-in functors in index order (pl-funct.c)."
function registerBuiltinFunctors(functors::functors_t)::Nothing
    functors.statistics_functors = length(_BUILTIN_FUNCTORS)
    for (a, arity) in _BUILTIN_FUNCTORS
        name = (UInt64(a) << LMASK_BITS) | TAG_ATOM
        v = pointerHashValue(name, functors.table.buckets) + 1
        f = functorDef(
            functors.table.table[v], UInt64(0), name, arity, UInt32(0),
            FUNCTOR_PERMANENT_REF, nothing
        )                                               # f->references = FUNCTOR_PERMANENT_REF; f->next_free = NULL
        functors.table.table[v] = f
        addFunctorToArray(functors, f)
    end
    return nothing
end

# ORIGINAL: `FUNCTOR_<id><arity>` of the generated pl-funct.ih, by the name's atom id and the arity.
"The word of the built-in functor `FUNCTOR_<id><arity>` (pl-funct.ih)."
function builtin_functor(id::AbstractString, arity::Int)::UInt64
    a = findfirst(==(id), _BUILTIN_ATOM_IDS)
    k = a === nothing ? nothing : findfirst(==((a, arity)), _BUILTIN_FUNCTORS)
    k === nothing && throw(ArgumentError("no built-in functor FUNCTOR_$id$arity"))
    return MK_FUNCTOR(UInt64(k), arity < F_ARITY_MASK ? UInt64(arity) : F_ARITY_MASK)
end

# PORT: pl-funct.c registerControlFunctors
# DIVERGES: on one database's table; `O_CALL_AT_MODULE` is defined (pl-incl.h:236), so `@/2` is
# one. The compiler reads `ControlFunctors` (above) until stage C.
"Flag the control structures `CONTROL_F` on the table's definitions (pl-funct.c)."
function registerControlFunctors!(functors::functors_t)::Nothing
    for (id, n) in (
        ("comma", 2), ("semicolon", 2), ("bar", 2), ("ifthen", 2), ("softcut", 2),
        ("not_provable", 1), ("colon", 2), ("dollar", 1), ("at_sign", 2)
    )
        valueFunctor(functors, builtin_functor(id, n)).flags |= CONTROL_F
    end
    return nothing
end

# PORT: pl-funct.c registerArithFunctors
# DIVERGES: on one database's table. The compiler reads `_arith_functors` (above) until stage C.
"Flag the arithmetic comparisons and `is/2` `ARITH_F` on the table's definitions (pl-funct.c)."
function registerArithFunctors!(functors::functors_t)::Nothing
    for id in
        ("ar_equals", "ar_not_equal", "smaller", "larger", "smaller_equal", "larger_equal",
        "is")
        valueFunctor(functors, builtin_functor(id, 2)).flags |= ARITH_F
    end
    return nothing
end

# PORT: pl-funct.c initFunctors
# DIVERGES: once per database, on its own table, after its atom table (`initAtoms` is the caller's:
# `PL_global_data` builds `atoms` first); no `L_FUNCTOR` lock.
"Initialise the functor table (pl-funct.c): the hash table, the built-ins, their flags."
function initFunctors!(functors::functors_t)::functors_t
    if functors.table.buckets == 0                      # !functorDefTable
        allocFunctorTable(functors)
        functors.highest = 1
        registerBuiltinFunctors(functors)
        functors.builtin = functors.highest             # GD->functors.builtin
        registerControlFunctors!(functors)
        registerArithFunctors!(functors)
    end
    return functors
end
