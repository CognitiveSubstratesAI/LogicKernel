# THE ATOM TABLE (L1b stage A; the user's decision of 2026-10-14, L1 plan §2c): an atom is an
# INDEX into this table, as upstream's `atom_t` is, because a Julia `Symbol` cannot live in a
# `UInt64` cell. An atom is text + length (bytes) + blob type, so it can hold the character 0;
# `lookupBlob` finds or creates it by (bytes, length, type) — `same_name` compares `length` bytes,
# never a C string. Nothing reads the table yet except its tests: the slots switch to words in
# stage C, and the boundary then looks a symbol's text up here.
#
# Per database, as upstream's is per process (`GD->atoms`): `atoms_t`, held by `PL_global_data`
# (src/pl-global.jl). The built-in atoms are GENERATED from src/ATOMS at the pin by
# tools/gen_atoms.jl (upstream: `defatom` → pl-atom.ic), the empty atom first; a built-in atom's
# index is its position.
#
# SINGLE-THREADED. The lock-free paths reduce to their single-thread outcome: every
# `COMPARE_AND_SWAP_*` succeeds, the `goto redo` retries never happen, `acquire_atom_table` and
# `acquire_atom_bucket` are plain reads (upstream's non-O_PLMT definitions), and the rehash keeps
# no previous table for concurrent readers.
#
# NOT PORTED: atom GC (`collectAtoms`, `pl_garbage_collect_atoms`, `markAtom`, `unmarkAtoms`,
# `destroyAtom`, `invalidateAtom`, `considerAGC`, `AGC_wanted`, `register_atom`/`unregister_atom`,
# `bump_atom_references`, the type statistics `add_type_live`/…) — with pl-gc.c, the GC step (since L1; §2c):
# `references` is ported and set as upstream sets it, and nothing frees an atom; blob types other
# than text (`PL_unify_blob`, dead blobs, `PL_find_blob_type`, `PL_unregister_blob_type`); atom
# tracking (`track_atom/2`, O_DEBUG_ATOMGC); `pl_atom_hashstat`, `checkAtoms_src`,
# `resetListAtoms` (the `--traditional` switch), `exitAtoms`, `cleanupAtoms`, `atom_space`.

