# ORIGINAL: the interface symbol of each atom (L1b stage C6b; user, 2026-10-15), held by the
# DATABASE beside its atom table and shared by every engine made for it — no upstream counterpart: SWI's atom
# record IS its name, and every engine reads that one record. The atom table is not parametric in
# the term type, so the symbols are a store of their own, in the atom array's layout: 64 blocks,
# block `idx` holding the `2^idx` atoms from index `2^idx`, allocated whole and never moved (as
# `allocateAtomBlock`), so a reader in another engine never meets a reallocation (a `push!` could
# move a vector under it). An entry is filled when its atom gets its first word from a symbol
# (`_atom_word!`), the one place a symbol becomes an atom word.
# (L1c-6 kept each symbol's INDEX KEY beside it; since L1d step 4 an atom's key IS its word —
# pl-index.c `indexOfWord`, `case TAG_ATOM: break;` — so no key is stored: the symbols alone.)
"The interface symbol of each atom of one database's table, in the atom array's block layout (L1b C6b)."
struct atom_symbols{T}
    blocks::Vector{Union{Nothing, Vector{Union{Nothing, T}}}}   # as atom_array.blocks: 64 blocks
end

"An empty symbol store: no block allocated."
atom_symbols{T}() where {T} =
    atom_symbols{T}(Union{Nothing, Vector{Union{Nothing, T}}}[nothing for _ in 1:64])

# ORIGINAL: the symbol of the atom at `index`, read as `fetchAtomArray` reads the atom.
"The interface symbol of the atom at `index` in `s`, or `nothing` (none recorded)."
@inline function atomSymbol(s::atom_symbols{T}, index::Int)::Union{Nothing, T} where {T}
    idx = MSB(index)
    b = s.blocks[idx + 1]
    b === nothing && return nothing
    return b[index - (1 << idx) + 1]
end

# ORIGINAL: record the symbol of the atom at `index`, its block allocated whole first if it is not
# yet (as `allocateAtomBlock`).
"Record `v` as the interface symbol of the atom at `index` in `s`."
function setAtomSymbol!(s::atom_symbols{T}, index::Int, v::T)::Nothing where {T}
    idx = MSB(index)
    b = s.blocks[idx + 1]
    if b === nothing
        b = Union{Nothing, T}[nothing for _ in 1:(1 << idx)]
        s.blocks[idx + 1] = b
    end
    b[index - (1 << idx) + 1] = v
    return nothing
end

# ORIGINAL: `type->registered` of upstream, read off the database's registrations.
"The registration of blob type `type` in `atoms`, or `nothing`."
function _blob_registration(
    atoms::atoms_t, type::PL_blob_t
)::Union{Nothing, blob_registration}
    for r in atoms.types
        r.type === type && return r
    end
    return nothing
end

# PORT: pl-atom.c PL_register_blob_type
# DIVERGES: the registration is recorded in `atoms.types` (see `blob_registration`); `atom_name`
# is passed by the callers that set it before registering (`do_init_atoms!`: `ATOM_text`,
# `initReservedSymbols!`: `ATOM_reserved_symbol`), where upstream sets the type's field first —
# 0 makes it `PL_new_atom(type->name)`, as upstream.
"Register blob type `type` (pl-atom.c): its rank and padding, its name atom."
function PL_register_blob_type(
    atoms::atoms_t, type::PL_blob_t, atom_name::UInt64=UInt64(0)
)::blob_registration
    r = _blob_registration(atoms, type)
    r === nothing || return r
    r = blob_registration(type, 0, 0, atom_name)
    push!(atoms.types, r)                               # the `next` chain: at its end
    if type.flags & PL_BLOB_TEXT != 0
        r.rank = (atoms.text_rank += 1)
        r.padding = type.flags & PL_BLOB_WCHAR != 0 ? sizeof(UInt32) : sizeof(UInt8)
    else
        r.rank = (atoms.nontext_rank -= 1)
    end
    if r.atom_name == 0
        r.atom_name = lookupAtom(atoms, Vector{UInt8}(codeunits(type.name)))
    end
    return r
end

# PORT: pl-atom.c allocateAtomBlock
# DIVERGES: block `idx` is a vector of `2^idx` atoms, `blocks[idx + 1]`, indexed from 1
# (upstream offsets the pointer by `-bs` to index it directly; see `fetchAtomArray`).
"Allocate block `idx` of the atom array (pl-atom.c): `2^idx` invalid atoms."
function allocateAtomBlock(atoms::atoms_t, idx::Int)::Nothing
    if atoms.array[idx + 1] === nothing
        bs = 1 << idx
        newblock = Vector{atom}(undef, bs)
        for i in 1:bs
            newblock[i] = atom(
                nothing, UInt64(0), UInt32(0), UInt32(0), ATOM_TYPE_INVALID, 0,
                Vector{UInt8}(codeunits("<virgin>"))
            )
        end
        atoms.array[idx + 1] = newblock
    end
    return nothing
end

# PORT: pl-atom.c reserveAtom
"Reserve the next free atom slot (pl-atom.c): a hole below `highest`, else `highest`."
function reserveAtom(atoms::atoms_t)::atom
    # O_ATOMGC: try to find a hole!
    index = atoms.no_hole_before
    i = MSB(index)
    last = false
    while !last
        upto = 2 << i
        high = atoms.highest
        if upto >= high
            upto = high
            last = true
        end
        b = atoms.array[i + 1]
        while index < upto
            a = (b::Vector{atom})[index - (1 << i) + 1]
            ref = a.references
            if ATOM_IS_FREE(ref)
                a.references = ATOM_RESERVED_REFERENCE      # COMPARE_AND_SWAP_UINT
                @assert a.type === ATOM_TYPE_INVALID
                atoms.no_hole_before = index + 1
                a.atom = (UInt64(index) << LMASK_BITS) | TAG_ATOM
                return a
            end
            index += 1
        end
        i += 1
    end
    atoms.no_hole_before = index + 1

    while true
        index = atoms.highest
        idx = MSB(index)
        atoms.array[idx + 1] === nothing && allocateAtomBlock(atoms, idx)
        a = fetchAtomArray(atoms, index)
        ref = a.references
        if ATOM_IS_FREE(ref)
            a.references = ATOM_RESERVED_REFERENCE          # COMPARE_AND_SWAP_UINT
            atoms.highest = index + 1                       # COMPARE_AND_SWAP_SIZE
            a.atom = (UInt64(index) << LMASK_BITS) | TAG_ATOM
            return a
        end
    end
end

# PORT: pl-atom.c same_name
"`a`'s name is the `length` bytes of `s` (pl-atom.c): never a C-string comparison."
function same_name(a::atom, s::AbstractVector{UInt8}, length::Int, type::PL_blob_t)::Bool
    if type.flags & PL_BLOB_NOCOPY == 0
        return length == 0 || view(s, 1:length) == view(a.name, 1:length)
    else
        return s === a.name
    end
end

# PORT: pl-atom.c lookupBlob
# DIVERGES: single-threaded (see the file header); returns `(atom_t, new)` where upstream writes
# `*new`; `PL_BLOB_NOCOPY` types hash the bytes too (the kernel has no pointer to hash; NOCOPY
# types are not ported). NOT PORTED: `considerAGC` every 128th atom, the type's `acquire` hook
# (text types have none), `add_type_live`.
"""
    lookupBlob(atoms, s, length, type) -> (atom_t, new)

The atom of type `type` whose name is the `length` bytes of `s`, created if there is none
(pl-atom.c): `new` says it was created.
"""
function lookupBlob(
    atoms::atoms_t, s::AbstractVector{UInt8}, length::Int, type::PL_blob_t
)::Tuple{UInt64, Bool}
    reg = _blob_registration(atoms, type)
    reg === nothing && (reg = PL_register_blob_type(atoms, type))   # avoid deadlock

    v0 = MurmurHashAligned2(s, length, MURMUR_SEED)
    table, buckets = atoms.table.table, atoms.table.buckets           # acquire_atom_table
    v = (v0 & UInt32(buckets - 1)) + 1
    head = table[v]

    if type.flags & PL_BLOB_UNIQUE != 0
        a = table[v]
        while a !== nothing
            ref = a.references
            if ATOM_IS_RESERVED(ref) && length == a.length && type === a.type &&
                same_name(a, s, length, type)
                @assert ATOM_IS_VALID(ref)              # !ATOM_IS_VALID: goto redo (threads)
                return a.atom, false
            end
            a = a.next
        end
    end

    if atoms.table.buckets * 2 < atoms.statistics_atoms
        rehashAtoms(atoms)
        table = atoms.table.table                       # goto redo: the new table
        v = (v0 & UInt32(atoms.table.buckets - 1)) + 1
        head = table[v]
    end

    a = reserveAtom(atoms)
    a.length = length
    a.type = type
    if type.flags & PL_BLOB_NOCOPY == 0
        pad = reg.padding
        name = zeros(UInt8, length + pad)               # memcpy, then memset(pad)
        copyto!(name, 1, s, 1, length)
        a.name = name
    else
        a.name = s isa Vector{UInt8} ? s : Vector{UInt8}(s)
    end
    a.hash_value = v0                                   # O_TERMHASH

    if type.flags & PL_BLOB_UNIQUE != 0
        a.next = head
        table[v] = a                                    # COMPARE_AND_SWAP_PTR
    end
    a.references = UInt32(1) | ATOM_VALID_REFERENCE | ATOM_RESERVED_REFERENCE   # O_ATOMGC
    atoms.statistics_atoms += 1
    return a.atom, true
end

# PORT: pl-atom.c lookupAtom
"The text atom whose name is the ISO Latin-1 bytes `s` (pl-atom.c), created if new."
lookupAtom(atoms::atoms_t, s::AbstractVector{UInt8}, length::Int=Base.length(s))::UInt64 =
    first(lookupBlob(atoms, s, length, text_atom))

# PORT: pl-atom.c rehashAtoms
# DIVERGES: no previous table is kept (`newtab->prev`: concurrent readers); always succeeds.
# NOT PORTED: the `GD->halt.cleaning` early return (no halt).
"Double the atom hash table and re-chain every unique atom (pl-atom.c)."
function rehashAtoms(atoms::atoms_t)::Bool
    atoms.table.buckets * 2 >= atoms.statistics_atoms && return true
    newtab = atom_table(atoms.table.buckets * 2, Union{Nothing, atom}[])
    newtab.table = Union{Nothing, atom}[nothing for _ in 1:(newtab.buckets)]
    mask = UInt32(newtab.buckets - 1)
    atoms.rehashing = true
    index = 1
    i = 0
    last = false
    while !last
        upto = 2 << i
        high = atoms.highest
        if upto >= high
            upto = high
            last = true
        end
        b = atoms.array[i + 1]
        while index < upto
            a = (b::Vector{atom})[index - (1 << i) + 1]
            ref = a.references
            if ATOM_IS_RESERVED(ref)
                @assert ATOM_IS_VALID(ref)              # !ATOM_IS_VALID: goto redo (threads)
                if a.type.flags & PL_BLOB_UNIQUE != 0
                    v = (a.hash_value & mask) + 1
                    a.next = newtab.table[v]
                    newtab.table[v] = a
                end
            end
            index += 1
        end
        i += 1
    end
    atoms.table = newtab
    atoms.rehashing = false
    return true
end

# PORT: pl-atom.c registerBuiltinAtoms
# DIVERGES: the names are the generated `_BUILTIN_ATOMS` (upstream: the static `atoms[]` of
# pl-atom.ic), copied into the atom; always the SWI-7 list atom (`"."` → `"[|]"`: no
# `--traditional`).
"Load the built-in atoms in index order (pl-atom.c), `.` as `[|]`."
function registerBuiltinAtoms(atoms::atoms_t)::Nothing
    size = length(_BUILTIN_ATOMS)
    atoms.statistics_atoms = size
    index = atoms.highest
    for s0 in _BUILTIN_ATOMS
        idx = MSB(index)
        atoms.array[idx + 1] === nothing && allocateAtomBlock(atoms, idx)
        s = s0 == "." ? "[|]" : s0                      # && !GD->options.traditional
        bytes = Vector{UInt8}(codeunits(s))
        len = length(bytes)
        v0 = MurmurHashAligned2(bytes, len, MURMUR_SEED)
        v = (v0 & UInt32(atoms.table.buckets - 1)) + 1
        a = fetchAtomArray(atoms, index)
        a.atom = (UInt64(index) << LMASK_BITS) | TAG_ATOM
        a.name = bytes
        a.length = len
        a.type = text_atom
        a.references = ATOM_VALID_REFERENCE | ATOM_RESERVED_REFERENCE  # O_ATOMGC
        a.hash_value = v0                               # O_TERMHASH
        a.next = atoms.table.table[v]
        atoms.table.table[v] = a
        atoms.no_hole_before = index + 1
        atoms.highest = index + 1
        index += 1
    end
    return nothing
end

# PORT: pl-atom.c lockAtoms
"Make every atom so far built-in: never collected (pl-atom.c)."
function lockAtoms(atoms::atoms_t)::Nothing
    atoms.builtin = atoms.highest
    atoms.unregistered = 0
    return nothing
end

# ORIGINAL: `ATOM_<id>` of the generated pl-atom.ih, by its id: the word of built-in atom `id`.
"The word of the built-in atom `ATOM_<id>` (pl-atom.ih), by its position in `_BUILTIN_ATOM_IDS`."
function builtin_atom(id::AbstractString)::UInt64
    i = findfirst(==(id), _BUILTIN_ATOM_IDS)
    i === nothing && throw(ArgumentError("no built-in atom ATOM_$id"))
    return (UInt64(i) << LMASK_BITS) | TAG_ATOM
end

# PORT: pl-atom.c do_init_atoms
# DIVERGES: once per database, on its own table (upstream: once per process, under
# `L_INIT_ATOMS`); `text_atom`'s name atom is passed to the registration (see
# `PL_register_blob_type`). NOT PORTED: `initPrologThreads`, the hash statistics' halt hook.
"Initialise the atom table (pl-atom.c): the hash table, the built-in atoms, the blob types."
function do_init_atoms!(atoms::atoms_t)::atoms_t
    if !atoms.initialised
        atoms.table = atom_table(
            ATOMHASHSIZE, Union{Nothing, atom}[nothing for _ in 1:ATOMHASHSIZE]
        )
        atoms.highest = 1
        atoms.no_hole_before = 1
        registerBuiltinAtoms(atoms)
        atoms.margin = 10000                            # O_ATOMGC
        lockAtoms(atoms)
        PL_register_blob_type(atoms, text_atom, builtin_atom("text"))
        initReservedSymbols!(atoms)                     # O_RESERVED_SYMBOLS
        atoms.initialised = true
    end
    return atoms
end
